// Generates integrations/cloud/assets.mjs: the static site and the MCP view embedded for the cloud worker.
import {readFile,readdir,writeFile} from 'node:fs/promises';
import {extname} from 'node:path';
const root=new URL('../',import.meta.url);
const types={'.html':'text/html; charset=utf-8','.css':'text/css; charset=utf-8','.mjs':'text/javascript; charset=utf-8','.js':'text/javascript; charset=utf-8','.svg':'image/svg+xml'};
export async function buildWorkerAssets(){
 const assets={};
 for(const dir of ['web','core'])for(const name of await readdir(new URL(dir+'/',root))){
  if(!types[extname(name)])continue;
  const route=(dir==='web'?'/':'/core/')+name;
  assets[route]={type:types[extname(name)],body:(await readFile(new URL(dir+'/'+name,root))).toString('base64')};
 }
 const ui=await readFile(new URL('web/mcp-app.html',root),'utf8');
 const source='// Generated by scripts/build-worker.mjs — do not edit.\nexport const ASSETS='+JSON.stringify(assets)+';\nexport const UI_HTML='+JSON.stringify(ui)+';\n';
 await writeFile(new URL('integrations/cloud/assets.mjs',root),source);
 return {routes:Object.keys(assets).length,bytes:source.length};
}
if(import.meta.url===`file://${process.argv[1]}`)console.log(await buildWorkerAssets());
